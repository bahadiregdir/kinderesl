export function getAllWorksheets(): Worksheet[] {
  return worksheets;
}

export function getWorksheetBySlug(slug: string): Worksheet | undefined {
  return worksheets.find((w) => w.slug === slug);
}

export function getWorksheetsByCategory(category: string): Worksheet[] {
  return worksheets.filter((w) => w.category === category);
}

export function getWorksheetsByTheme(theme: string): Worksheet[] {
  return worksheets.filter((w) => w.theme === theme);
}

export function getWorksheetsByMonth(month: string): Worksheet[] {
  return worksheets.filter((w) => w.monthTheme?.toLowerCase() === month.toLowerCase());
}

export function getRelatedWorksheets(currentSlug: string, count: number = 3): Worksheet[] {
  const current = getWorksheetBySlug(currentSlug);
  if (!current) return worksheets.slice(0, count);

  const explicit: Worksheet[] = [];
  for (const slug of current.relatedSlugs) {
    const found = getWorksheetBySlug(slug);
    if (found && found.slug !== currentSlug) {
      explicit.push(found);
    }
  }

  if (explicit.length >= count) {
    return explicit.slice(0, count);
  }

  const others = worksheets.filter(
    (w) => w.slug !== currentSlug && !explicit.some((e) => e.slug === w.slug)
  );
  return [...explicit, ...others].slice(0, count);
}
